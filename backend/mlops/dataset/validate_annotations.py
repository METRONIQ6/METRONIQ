import os
import glob
import cv2

def validate_dataset(images_dir, labels_dir):
    image_files = glob.glob(os.path.join(images_dir, "*.*"))
    
    total_images = len(image_files)
    valid_count = 0
    warning_count = 0
    fail_count = 0
    
    print("====================================")
    print("METRONIQ ANNOTATION VALIDATOR")
    print("====================================")
    
    if total_images == 0:
        print("[FAIL] No images found. Real dataset is MISSING.")
        return
        
    for img_path in image_files:
        base = os.path.basename(img_path)
        name, _ = os.path.splitext(base)
        label_path = os.path.join(labels_dir, f"{name}.txt")
        
        if not os.path.exists(label_path):
            print(f"[WARN] Missing label file for {base}. Assuming background/empty.")
            warning_count += 1
            continue
            
        img = cv2.imread(img_path)
        if img is None:
            print(f"[FAIL] Image corrupt but present: {base}")
            fail_count += 1
            continue
            
        with open(label_path, 'r') as f:
            lines = f.readlines()
            
        valid = True
        if not lines:
            print(f"[WARN] Empty label file for {base}")
            warning_count += 1
            continue
            
        for line in lines:
            parts = line.strip().split()
            if len(parts) != 5:
                print(f"[FAIL] Invalid label syntax in {name}.txt: {line.strip()}")
                valid = False
                break
                
            try:
                cls_id = int(parts[0])
                rx, ry, rw, rh = map(float, parts[1:])
                if cls_id < 0 or cls_id > 5:
                    print(f"[FAIL] Out of bounds class ID ({cls_id}) in {name}.txt")
                    valid = False
                    break
                if not (0.0 <= rx <= 1.0 and 0.0 <= ry <= 1.0 and 0.0 <= rw <= 1.0 and 0.0 <= rh <= 1.0):
                    print(f"[FAIL] Unnormalized coordinates in {name}.txt: {rx}, {ry}, {rw}, {rh}")
                    valid = False
                    break
            except Exception:
                print(f"[FAIL] Parsing error in {name}.txt")
                valid = False
                break
                
        if valid:
            valid_count += 1
        else:
            fail_count += 1

    print("\n[VALIDATION SUMMARY]")
    print(f"Total Images Checked: {total_images}")
    print(f"Valid Annotations: {valid_count}")
    print(f"Warnings (Missing/Empty labels): {warning_count}")
    print(f"Fails (Corrupt geometry/syntax): {fail_count}")

    with open("DATASET_REPORT.md", "w") as rep:
        rep.write("# DATASET VALIDATION REPORT\n\n")
        rep.write(f"- Total Images: {total_images}\n")
        rep.write(f"- Valid Annotations: {valid_count}\n")
        rep.write(f"- Hard Fails: {fail_count}\n")
        rep.write("\n_Auto-generated by MetronIQ Validator._")

if __name__ == "__main__":
    validate_dataset("images/train", "labels/train")
