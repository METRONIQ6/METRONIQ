def translate_status(status, lang: str = "en") -> str:
    if not status:
        return "N/A"
    status_str = str(status).strip()
    if lang == "en":
        return status_str.replace("_", " ").title()
    dict_map = INTERNAL_STATUS_TRANSLATIONS.get(lang, {})
    if isinstance(dict_map, dict):
        return dict_map.get(status_str.upper(), dict_map.get(status_str, status_str))
    return status_str
