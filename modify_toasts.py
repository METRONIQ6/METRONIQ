for json_file, data_dict in [("en.json", toast_dict), ("ta.json", ta_map), ("hi.json", hi_map)]:
    path = f"frontend/src/i18n/locales/{json_file}"
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    if "toast" not in data:
        data["toast"] = {}
    
    for en_key, val in data_dict.items():
        dict_key = toast_dict[en_key]
        prefix, key_name = dict_key.split('.')
        if prefix not in data:
            data[prefix] = {}
        data[prefix][key_name] = val
        
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=4, ensure_ascii=False)

def replace_toasts(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    original = content
    # Look for literal toast strings and replace with t(...)
    # e.g., toast({ type: "error", message: "Network anomaly..." }) -> toast({ type: "error", message: t("error.notices_fetch") })
    
    # We will do simple string replacement since we have exact strings
    for en_txt, dict_key in toast_dict.items():
        if en_txt.endswith(": "):
            continue # Hard to generic replace without template literals
        
        # Replace double quotes
        content = content.replace(f'message: "{en_txt}"', f'message: t("{dict_key}")')
        # Replace single quotes
        content = content.replace(f"message: '{en_txt}'", f'message: t("{dict_key}")')

    if content != original:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Toasts injected into {filepath}")

for root, _, files in os.walk("frontend/src"):
    for file in files:
        if file.endswith(".tsx"):
            replace_toasts(os.path.join(root, file))

print("Toasts processed.")
